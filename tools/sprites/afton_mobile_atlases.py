"""Pack Michael and both Springtrap variants without rebuilding older atlases.

Run after afton_costume.py. Pixels, frame numbers, logical canvas and foot pivots
are retained; trimmed atlases avoid allocating the large empty move grids on phones.
"""
from pathlib import Path
from PIL import Image
import hashlib
import json
import re

ROOT=Path(__file__).resolve().parents[2]


def pack(key,folder,image_path=None,frame_size=(112,104)):
    """Trim and deduplicate one move grid while keeping every numeric frame."""
    im=Image.open(image_path or ROOT/'public/assets/fighters/last-seen/afton'/folder/'moves_sheet.png').convert('RGBA')
    fw,fh=frame_size;cols=im.width//fw;cells=[];unique=[];seen={}
    for i in range(cols*(im.height//fh)):
        cel=im.crop((i%cols*fw,i//cols*fh,i%cols*fw+fw,i//cols*fh+fh));b=cel.getbbox() or (0,0,1,1)
        b=(max(0,b[0]-2),max(0,b[1]-2),min(fw,b[2]+2),min(fh,b[3]+2));trim=cel.crop(b)
        signature=(trim.size,hashlib.sha256(trim.tobytes()).digest())
        if signature not in seen:seen[signature]=len(unique);unique.append(trim)
        cells.append((seen[signature],b))
    width=2048;x=y=row=0;positions=[]
    for cel in unique:
        w,h=cel.size
        if x+w>width:x=0;y+=row;row=0
        positions.append((x,y));x+=w;row=max(row,h)
    height=y+row;assert height<=4096
    atlas=Image.new('RGBA',(width,height))
    for cel,(x,y) in zip(unique,positions):atlas.paste(cel,(x,y))
    frames={}
    for i,(index,b) in enumerate(cells):
        x,y=positions[index];w,h=unique[index].size
        frames[str(i)]={'frame':{'x':x,'y':y,'w':w,'h':h},'rotated':False,'trimmed':True,'spriteSourceSize':{'x':b[0],'y':b[1],'w':w,'h':h},'sourceSize':{'w':fw,'h':fh}}
    stem='assets/mobile/'+key
    original={'width':im.width,'height':im.height,'frameWidth':fw,'frameHeight':fh,'columns':cols}
    atlas.save(ROOT/'public'/(stem+'.png'),optimize=True)
    data={'frames':frames,'meta':{'app':'REBIRTH lossless mobile packer','original':original}}
    (ROOT/'public'/(stem+'.json')).write_text(json.dumps(data,separators=(',',':')))
    return {'image':stem+'.png','json':stem+'.json','original':original},im.width*im.height*4,width*height*4


def main():
    """Append only new costume atlas registrations and update the memory report."""
    path=ROOT/'src/mobileAtlasManifest.js';text=path.read_text()
    manifest=json.loads(re.search(r'export const MOBILE_ATLASES\s*=\s*([^;]+);',text).group(1))
    report_path=ROOT/'public/assets/mobile/report.json';report=json.loads(report_path.read_text())
    before=report['originalBytes'];after=report['packedBytes']
    for key,folder in [('ls_afton_moves',''),('ls_wrong_afton_moves','wrong'),('ls_wrong_afton_noaxe_moves','wrong/noaxe')]:
        # Re-running replaces the same atlas without double-counting its memory.
        if key in manifest:
            old=manifest[key];o=old['original'];before-=o['width']*o['height']*4
            with Image.open(ROOT/'public'/old['image']) as image:after-=image.width*image.height*4
        manifest[key],raw,packed=pack(key,folder);before+=raw;after+=packed
    path.write_text('// Generated by mobile_atlases.py; Afton additions by afton_mobile_atlases.py\nexport const MOBILE_ATLASES='+json.dumps(manifest,separators=(',',':'))+';\n')
    report_path.write_text(json.dumps({'sheets':len(manifest),'originalBytes':before,'packedBytes':after,'savedPercent':round((1-after/before)*100,1)}))
    print('Packed three Afton move sets; retained numeric frames and foot pivots.')


if __name__=='__main__':
    main()
