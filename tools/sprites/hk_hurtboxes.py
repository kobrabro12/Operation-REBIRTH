"""Lacy's hurtboxes, frame by frame: for every frame of her strips, the box round her BODY (not the sword or the
see-through slash arcs) measured from her feet while facing right -> src/fighters/hkHurt.js (generated).
Her drawings lunge, crouch and twist a lot inside big frames, so one fixed box never matched where she really is.
How: only fully solid pixels count (the arcs are half see-through), thin lines (the blade) are opened away, the
biggest blob left is her, and its box is shrunk a little so grazing hits feel fair."""
from PIL import Image
import numpy as np, os, json
from scipy import ndimage

HERE = os.path.dirname(__file__)
DIR = os.path.join(HERE, '..', '..', 'public', 'assets', 'fighters', 'hero-knight')
OUT = os.path.join(HERE, '..', '..', 'src', 'fighters', 'hkHurt.js')
SHEETS = {   # strip -> frame size and where her feet are in it
    **{k: (150, 90, 66, 86) for k in ['idle', 'run', 'attack1', 'attack2', 'jump', 'fall', 'hit', 'death', 'guard', 'grab',
                                       'idle_u', 'run_u', 'jump_u', 'fall_u', 'hit_u']},
    'moves': (180, 140, 81, 111),
}
SHRINK = 2          # pixels taken off each side of the measured box
MIN_W, MIN_H = 16, 22

table = {}
for k, (fw, fh, ox, oy) in SHEETS.items():
    p = os.path.join(DIR, k + '_sheet.png')
    if not os.path.exists(p): continue
    a = np.array(Image.open(p).convert('RGBA'))[..., 3]
    rows = a.shape[0] // fh; cols = a.shape[1] // fw; boxes = []
    for i in range(rows * cols):
        r, c = divmod(i, cols)
        m = a[r * fh:(r + 1) * fh, c * fw:(c + 1) * fw] == 255
        m = ndimage.binary_opening(m, structure=np.ones((3, 3)))          # the blade is a thin line: gone
        lab, n = ndimage.label(m)
        if n == 0: boxes.append(None); continue
        sizes = ndimage.sum(m, lab, range(1, n + 1)); big = np.argmax(sizes) + 1
        # her body: the biggest blob, plus any other big pieces close to it (an arm cut off by the opening)
        keep = lab == big
        for j in range(1, n + 1):
            if j != big and sizes[j - 1] > 25: keep |= lab == j
        ys, xs = np.nonzero(keep)
        # her legs can be thin enough to open away: take the bottom from the whole drawing under her body
        raw = a[r * fh:(r + 1) * fh, c * fw:(c + 1) * fw] == 255
        under = raw[:, max(0, xs.min() - 4):xs.max() + 5]; uy = np.nonzero(under.any(1))[0]
        ys = np.append(ys, min(uy.max(), ys.max() + 14))   # (but not all the way down a sword pointed at the floor)
        x1, x2, y1, y2 = xs.min() + SHRINK - ox, xs.max() + 1 - SHRINK - ox, ys.min() + SHRINK - oy, ys.max() + 1 - oy
        if x2 - x1 < MIN_W: cx = (x1 + x2) / 2; x1, x2 = round(cx - MIN_W / 2), round(cx + MIN_W / 2)
        if y2 - y1 < MIN_H: y1 = y2 - MIN_H
        boxes.append([int(x1), int(y1), int(x2), int(y2)])
    table[k] = boxes

with open(OUT, 'w') as f:
    f.write('// Generated by tools/sprites/hk_hurtboxes.py - do not edit by hand.\n')
    f.write("// Lacy's hurtbox for every frame of her strips: [x1, y1, x2, y2] from her feet, facing right (null = use body).\n")
    f.write('export const HK_HURT = {\n')
    for k, v in table.items(): f.write('  ' + json.dumps(k) + ': ' + json.dumps(v, separators=(',', ':')) + ',\n')
    f.write('};\n')
print({k: len(v) for k, v in table.items()}, table['idle'][0], table['guard'])
